// Run: node scripts/gen-icon.mjs  (writes docs/images/agate-logo.svg, docs/images/agate-icon.svg, src/icon.ts)
// Generates the Agate icon: a simplified, rounded agate slice with concentric bands.
// Outline = smooth closed curve through control points; bands = the same outline scaled
// about a centre that drifts toward an off-centre core, so bands thin on one side like a real slice.
import { writeFileSync } from "fs";

const pts = [ // rounded slice: broad convex top, bulging right side, tapering to the lower left (like the photo)
  [34, 7], [60, 5], [82, 14], [95, 38], [92, 64], [74, 88], [46, 96], [22, 86], [8, 64], [7, 38], [18, 16],
];
function smoothPath(points, cx, cy, s) {
  const P = points.map(([x, y]) => [cx + (x - cx) * s, cy + (y - cy) * s]);
  const n = P.length; let d = `M${P[0][0].toFixed(2)},${P[0][1].toFixed(2)}`;
  for (let i = 0; i < n; i++) {
    const p0 = P[(i - 1 + n) % n], p1 = P[i], p2 = P[(i + 1) % n], p3 = P[(i + 2) % n];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += ` C${c1[0].toFixed(2)},${c1[1].toFixed(2)} ${c2[0].toFixed(2)},${c2[1].toFixed(2)} ${p2[0].toFixed(2)},${p2[1].toFixed(2)}`;
  }
  return d + " Z";
}
const outer = [51, 50], core = [40, 58];           // bands drift toward a lower-left core
const centre = (t) => [outer[0] + (core[0] - outer[0]) * t, outer[1] + (core[1] - outer[1]) * t];

// Colour logo: bands from the photo (dark rim, cream, amber, red-brown, white, deep red, pink core, pale cavity)
const bands = [
  [1.00, "#3b2320"], [0.94, "#f3e7d3"], [0.89, "#d8892b"], [0.82, "#a8351f"], [0.75, "#f3e7d3"],
  [0.71, "#e3a13c"], [0.62, "#8e2418"], [0.53, "#f7efe3"], [0.48, "#b8452a"], [0.38, "#e4bfb4"],
  [0.24, "#faf3ec"],
];
let colour = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="256" height="256">\n`;
bands.forEach(([s, fill], i) => { const [cx, cy] = centre(1 - s); colour += `  <path d="${smoothPath(pts, cx, cy, s)}" fill="${fill}"/>\n`; });
colour += `</svg>\n`;
writeFileSync(new URL("../docs/images/agate-logo.svg", import.meta.url), colour);

// Monochrome UI icon: outlines only, currentColor, lucide-like weight. Obsidian's addIcon draws
// the inner SVG content on a 100x100 viewBox.
const rings = [1.0, 0.68, 0.36];
let inner = "";
rings.forEach((s) => { const [cx, cy] = centre(1 - s); inner += `<path d="${smoothPath(pts, cx, cy, s)}" fill="none" stroke="currentColor" stroke-width="8" stroke-linejoin="round"/>`; });
writeFileSync(new URL("../src/icon.ts", import.meta.url), `// Generated by scripts/gen-icon.mjs; do not edit by hand.\n// Inner SVG content for Obsidian addIcon(), drawn on a 100x100 viewBox.\nexport const AGATE_ICON_ID = "agate";\nexport const AGATE_ICON_SVG =\n  ${JSON.stringify(inner)};\n`);
writeFileSync(new URL("../docs/images/agate-icon.svg", import.meta.url), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="128" height="128" style="color:#333">${inner}</svg>\n`);
console.log("ok", colour.length, inner.length);
