// Run: node scripts/build-icons.mjs
// Builds the Agate icons from the hand-finished source SVGs in docs/images/src/:
//   agate-icon.svg        detailed version -> docs/images/agate-logo.svg (README / repo logo, brick orange)
//   agate-icon-small.svg  simpler version  -> src/icon.ts (Obsidian addIcon, currentColor)
//                                             docs/images/agate-icon.svg (preview of the UI icon)
// Each source is a single even-odd path. Its points are rescaled into a 100x100 box (aspect kept,
// centred), which is the coordinate space Obsidian's addIcon() expects.
import { readFileSync, writeFileSync } from "fs";

const BRICK = "#C0502E";
const MARGIN = 2; // viewBox units left free on the long side
const url = (p) => new URL(p, import.meta.url);

function fit(file) {
  const svg = readFileSync(url(file), "utf8");
  const [, vw, vh] = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/).map(Number);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)];
  if (paths.length !== 1) throw new Error(`${file}: expected one <path>, found ${paths.length}`);
  const d = paths[0][1];
  if (/[^MZ\d\s,.-]/.test(d)) throw new Error(`${file}: only M/Z polygon paths are supported`);
  const s = (100 - 2 * MARGIN) / Math.max(vw, vh);
  const ox = (100 - vw * s) / 2, oy = (100 - vh * s) / 2;
  const f = (v) => +v.toFixed(2);
  return d.replace(/(-?[\d.]+),(-?[\d.]+)/g, (_, x, y) => `${f(x * s + ox)},${f(y * s + oy)}`)
    .replace(/\s+/g, " ").trim();
}

const logo = fit("../docs/images/src/agate-icon.svg");
const icon = fit("../docs/images/src/agate-icon-small.svg");

writeFileSync(
  url("../docs/images/agate-logo.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="256" height="256">` +
    `<path fill="${BRICK}" fill-rule="evenodd" d="${logo}"/></svg>\n`,
);

// Obsidian styles .svg-icon with fill:none + stroke:currentColor, so the path sets both explicitly.
const inner = `<path fill="currentColor" fill-rule="evenodd" stroke="none" d="${icon}"/>`;
writeFileSync(
  url("../src/icon.ts"),
  "// Generated by scripts/build-icons.mjs from docs/images/src/agate-icon-small.svg; do not edit by hand.\n" +
    "// Inner SVG content for Obsidian addIcon(), drawn on a 100x100 viewBox.\n" +
    'export const AGATE_ICON_ID = "agate";\n' +
    `export const AGATE_ICON_SVG =\n  ${JSON.stringify(inner)};\n`,
);
writeFileSync(
  url("../docs/images/agate-icon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="128" height="128" color="${BRICK}">${inner}</svg>\n`,
);
console.log(`logo ${logo.length} chars, icon ${icon.length} chars`);
